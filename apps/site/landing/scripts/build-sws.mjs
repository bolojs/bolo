// Generates the per-subsite service workers in public/<name>/sw.js from the
// single protocol source in packages/sw-sandbox/src/sw.ts. The hand-copied SW
// debt (see examples/app-builder/README) is fixed by deriving every subsite SW
// from initSW() so the protocol can evolve in one place.
//
// Run via `pnpm build:sw` (also wired into `pnpm build`).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";

const appDir = dirname(dirname(fileURLToPath(import.meta.url)));
const repoRoot = join(appDir, "../../..");
const swSourcePath = join(repoRoot, "packages/sw-sandbox/src/sw.ts");
const SUBSITES = ["ide", "sandbox", "app", "vibe"];

const source = readFileSync(swSourcePath, "utf8");
const { outputText } = ts.transpileModule(source, {
  compilerOptions: {
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
  },
  fileName: "sw.ts",
});

// The transpiled module keeps the `export` keyword; a classic (non-module)
// service worker script must not. initSW is the only export in sw.ts.
const script = outputText.replace(/export function initSW/, "function initSW");
if (script.includes("export ")) {
  throw new Error("sw.ts gained an export besides initSW; extend the build script");
}

const banner = `// Generated by scripts/build-sws.mjs from packages/sw-sandbox/src/sw.ts.
// Do not edit by hand; run \`pnpm build:sw\` in apps/site/landing instead.
`;

for (const name of SUBSITES) {
  const outPath = join(appDir, "public", name, "sw.js");
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, `${banner}\n${script}\ninitSW(self);\n`);
  console.log(`wrote ${outPath}`);
}
