/**
 * Predicates whose answer depends on V8 internals a browser container cannot
 * observe, so a divergence from Node here is expected and documented.
 */
const KNOWN_DIVERGENCES = new Set(["isExternal", "isProxy"]);

const values: Record<string, unknown> = {
  u8: new Uint8Array(4),
  stealthy: Object.setPrototypeOf(new Uint8Array(4), ArrayBuffer.prototype),
  fake: Object.create(Uint8Array.prototype),
  dv: new DataView(new ArrayBuffer(4)),
  ab: new ArrayBuffer(4),
  boxedBool: new Boolean(true),
  args: (function () {
    return arguments;
  })(),
  err: new Error("x"),
  asyncFn: async function () {},
  genFn: function* () {},
  mapIt: new Map()[Symbol.iterator](),
  plain: {},
};

describe("util.types (differential against Node)", () => {
  for (const [name, expected] of Object.entries(NODE_ORACLE)) {
    it(`matches Node for "${name}"`, () => {
      const value = values[name];
      for (const [predicate, nodeAnswer] of Object.entries(expected)) {
        if (KNOWN_DIVERGENCES.has(predicate)) continue;
        const actual = (types[predicate as keyof typeof types] as (v: unknown) => boolean)(value);
        expect(`${predicate}=${actual}`).toBe(`${predicate}=${nodeAnswer}`);
      }
    });
  }
});
